const ST = { on:false, q:[], i:0, id:null, cb:null, typing:null, full:"", pending:[] };
function storyState(){ if(!state.story) state.story = { seen:{}, flags:{} }; if(!state.story.seen) state.story.seen = {}; if(!state.story.flags) state.story.flags = {}; return state.story; }
/* 처음 한 번만 재생. 다른 창이 떠 있거나 전투 중이면 끝난 뒤에 이어서 나온다 */
function storyOnce(id, cb){
  if(!SCENES[id] || storyState().seen[id]){ if(cb) cb(); return; }
  storyState().seen[id] = true; ST.pending.push({ id, cb });
}
function storyReplay(id){ closeModal(); ST.pending.push({ id, cb:null, replay:true }); }
function storySpeaker(s){
  if(s === "narr") return null;
  const post = POSTS.find(p=>p.id === s), cid = post && state.posts && state.posts[post.id], n = cid && CREW_MAP[cid];
  if(n) return { name:n.name, role:`${post.ic} ${post.name}`, face:portrait(n, 86) };
  return { name:__("노바"), role:__("🤖 함선 항해 지능"), face:`<div style="width:86px;height:86px;border-radius:50%;flex:none;display:flex;align-items:center;justify-content:center;font-size:40px;background:radial-gradient(circle at 35% 30%,#5fe0ff,#1b2748 70%);border:2px solid #9ff3ff">🤖</div>` };
}
function storyStart(p){
  const sc = SCENES[p.id];
  ST.on = true; ST.id = p.id; ST.cb = p.cb; ST.replay = !!p.replay; ST.q = sc.lines.slice(); ST.i = 0;
  ST.wasPaused = paused; paused = true;
  $("scTitle").textContent = sc.title; $("scene").classList.add("on"); sfx("discover");
  storyShow();
}
function storyShow(){
  const node = ST.q[ST.i];
  if(!node){ storyEnd(); return; }
  const box = $("scBox"), ch = $("scChoices");
  ch.innerHTML = ""; clearInterval(ST.typing); ST.typing = null;
  if(node.c){
    box.style.display = "none";
    ch.innerHTML = node.c.map((c,k)=>`<button class="btn wide scChoice" onclick="event.stopPropagation();storyChoose(${k})">${c.t}</button>`).join("");
    return;
  }
  box.style.display = "flex";
  const sp = storySpeaker(node.s), txt = node.t.replace(/\{ship\}/g, SHIP_MAP[state.flagship].name);
  box.classList.toggle("narr", !sp);
  $("scFace").innerHTML = sp ? sp.face : ""; $("scWho").innerHTML = sp ? `${sp.name} <span>${sp.role}</span>` : "";
  ST.full = txt; const plain = txt.replace(/<[^>]+>/g, ""); let n = 0;
  $("scText").textContent = "";
  ST.typing = setInterval(()=>{ n += 2; $("scText").textContent = plain.slice(0, n);
    if(n >= plain.length){ clearInterval(ST.typing); ST.typing = null; $("scText").innerHTML = ST.full; } }, 28);
  if(sp) sfx("blip");
}
function storyNext(){
  if(!ST.on) return;
  const node = ST.q[ST.i]; if(node && node.c) return;                       /* 선택지에서는 골라야 넘어간다 */
  if(ST.typing){ clearInterval(ST.typing); ST.typing = null; $("scText").innerHTML = ST.full; return; }   /* 글자가 나오는 중이면 한 번에 표시 */
  ST.i++; storyShow();
}
function storyChoose(k){
  const c = ST.q[ST.i].c[k]; let extra = [];
  if(c.fx && !ST.replay){ const r = c.fx(state); if(r) extra = [{ s:"narr", t:r }]; }   /* 다시 보기에서는 보상이 없다 */
  ST.q.splice(ST.i, 1, ...(c.then||[]), ...extra); sfx("ok"); storyShow();
}
function storySkip(){ if(ST.on) storyEnd(); }
function storyEnd(){
  clearInterval(ST.typing); ST.typing = null; ST.on = false;
  $("scene").classList.remove("on"); paused = ST.wasPaused;
  const cb = ST.cb; ST.cb = null; updateHUD(); save();
  if(cb) cb();
}
document.addEventListener("keydown", e=>{ if(ST.on && (e.key === " " || e.key === "Enter")){ e.preventDefault(); storyNext(); } });

